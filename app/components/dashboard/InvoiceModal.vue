<script setup lang="ts">
import { LucideX, LucideDownload, LucideShare2 } from 'lucide-vue-next'
import { useToast } from '#imports'

const props = defineProps({
  isOpen: Boolean,
  transaction: {
    type: Object as () => any,
    required: false,
    default: null,
  },
})

const emit = defineEmits(['close'])
const toast = useToast()

const closeModal = () => emit('close')

const isPaid = computed(() => {
  const status = String(props.transaction?.status || props.transaction?.payment_status || '').toLowerCase()
  return ['success', 'finished', 'confirmed', 'paid', 'lunas'].includes(status)
})

const formatMoney = (amount: number | string | undefined) => {
  if (amount === undefined || amount === null) return '0.00 USDT'
  const isUsd = props.transaction?.currency === 'USD' || 
                props.transaction?.payment_data?.method?.includes('USDT') || 
                props.transaction?.payment_data?.method?.includes('TRC') ||
                props.transaction?.payment_data?.paymentName?.includes('USDT')
  if (isUsd) {
    return `${Number(amount).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} USDT`
  }
  return new Intl.NumberFormat('id-ID', { style: 'currency', currency: 'IDR', minimumFractionDigits: 0 }).format(Number(amount))
}

const formatDate = (dateString: string | undefined) => {
  if (!dateString) return '-'
  return new Intl.DateTimeFormat('en-US', {
    day: '2-digit', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit'
  }).format(new Date(dateString))
}

const downloadPdf = () => {
  const t = props.transaction
  const orderId = t?.payment_data?.merchantOrderId || t?.id?.substring(0,8) || '-'
  const total = formatMoney(Number(t?.amount || 0) + Number(t?.fee_amount || 0))
  const feeRow = Number(t?.fee_amount) > 0
    ? `<tr><td style="padding:10px 0;color:#374151;border-bottom:1px solid #f3f4f6">Service Fee</td><td style="padding:10px 0;color:#374151;border-bottom:1px solid #f3f4f6;text-align:right">${formatMoney(t?.fee_amount)}</td></tr>`
    : ''

  const statusBadge = isPaid.value 
    ? `<span class="badge" style="background:#dcfce7;color:#15803d">✓ PAID</span>`
    : `<span class="badge" style="background:#ffedd5;color:#c2410c">UNPAID / PENDING</span>`

  const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Invoice ${orderId}</title>
<style>
  @page { margin: 1.5cm; }
  body { font-family: 'Segoe UI', system-ui, -apple-system, sans-serif; color: #111827; margin: 0; padding: 2rem; }
  .header { display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 1.5rem; }
  .logo { height: 32px; }
  .title { font-size: 2rem; font-weight: 900; letter-spacing: 0.08em; margin: 0; }
  .badge { display: inline-block; padding: 3px 10px; font-size: 0.75rem; font-weight: 700; border-radius: 99px; margin-top: 4px; }
  .meta { margin-bottom: 1.5rem; }
  .meta-row { display: flex; justify-content: space-between; padding: 6px 0; font-size: 0.875rem; }
  .meta-label { color: #6b7280; }
  .meta-value { font-weight: 600; }
  hr { border: none; border-top: 1px solid #e5e7eb; margin: 0 0 1rem; }
  table { width: 100%; border-collapse: collapse; font-size: 0.875rem; }
  th { text-align: left; padding: 8px 0; font-weight: 700; font-size: 0.75rem; text-transform: uppercase; letter-spacing: 0.04em; border-bottom: 2px solid #111827; color: #374151; }
  th:last-child { text-align: right; }
  td { padding: 10px 0; color: #374151; border-bottom: 1px solid #f3f4f6; }
  .total td { padding-top: 12px; font-weight: 800; font-size: 1.1rem; color: #111827; border-top: 2px solid #111827; border-bottom: none; }
  .footer { margin-top: 2rem; text-align: center; font-size: 0.75rem; color: #9ca3af; }
</style>
</head><body>
<div class="header">
  <img src="${window.location.origin}/logo-full.png" class="logo" alt="Tentaklik" />
  <div style="text-align:right">
    <p class="title">INVOICE</p>
    ${statusBadge}
  </div>
</div>
<div class="meta">
  <div class="meta-row"><span class="meta-label">Invoice No.</span><span class="meta-value">${orderId}</span></div>
  <div class="meta-row"><span class="meta-label">Date</span><span class="meta-value">${formatDate(t?.created_at)}</span></div>
  <div class="meta-row"><span class="meta-label">Payment Method</span><span class="meta-value">${t?.payment_data?.paymentName || t?.payment_data?.method || 'Transfer'}</span></div>
</div>
<hr />
<table>
  <thead><tr><th>Item Description</th><th>Amount</th></tr></thead>
  <tbody>
    <tr><td style="padding:10px 0;color:#374151;border-bottom:1px solid #f3f4f6">${t?.description || 'Digital Ad Management Service'}</td><td style="padding:10px 0;color:#374151;border-bottom:1px solid #f3f4f6;text-align:right">${formatMoney(t?.amount)}</td></tr>
    ${feeRow}
  </tbody>
  <tfoot><tr class="total"><td>Total Payable</td><td style="text-align:right">${total}</td></tr></tfoot>
</table>
<div class="footer">
  <p>This document is an official payment invoice generated by Tentaklik.</p>
  <p>© ${new Date().getFullYear()} Tentaklik — tentaklik.com</p>
</div>
</body></html>`

  const printWindow = window.open('', '_blank', 'width=800,height=600')
  if (printWindow) {
    printWindow.document.write(html)
    printWindow.document.close()
    printWindow.onload = () => {
      printWindow.focus()
      printWindow.print()
      printWindow.onafterprint = () => printWindow.close()
      setTimeout(() => {
        try { if (!printWindow.closed) printWindow.close() } catch {}
      }, 1000)
    }
  }
}

const isSharing = ref(false)

const shareInvoice = async () => {
  if (!props.transaction) return
  isSharing.value = true

  try {
    const { toPng } = await import('html-to-image')
    const invoiceEl = document.getElementById('invoice-print-area')
    if (!invoiceEl) throw new Error('Invoice element not found')

    const dataUrl = await toPng(invoiceEl, {
      backgroundColor: '#ffffff',
      pixelRatio: 2,
      quality: 0.95
    })

    const res = await fetch(dataUrl)
    const blob = await res.blob()
    const file = new File([blob], `Invoice-${props.transaction?.payment_data?.merchantOrderId || 'Tentaklik'}.png`, { type: 'image/png' })

    if (navigator.canShare && navigator.canShare({ files: [file] })) {
      await navigator.share({
        title: `Invoice Tentaklik`,
        text: `Invoice Pembayaran Tentaklik #${props.transaction?.payment_data?.merchantOrderId}`,
        files: [file]
      })
      toast.addToast('Invoice shared successfully', 'success')
    } else {
      const link = document.createElement('a')
      link.download = `Invoice-${props.transaction?.payment_data?.merchantOrderId || 'Tentaklik'}.png`
      link.href = dataUrl
      link.click()
      toast.addToast('Invoice saved as PNG', 'success')
    }
  } catch (err: any) {
    console.error('Share invoice failed:', err)
    toast.addToast('Failed to share invoice', 'error')
  } finally {
    isSharing.value = false
  }
}
</script>

