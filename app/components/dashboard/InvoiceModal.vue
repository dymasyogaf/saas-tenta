      <div class="invoice-modal">
        <!-- Close Button -->
        <button @click="closeModal" class="invoice-close" title="Close">
          <LucideX class="w-4 h-4" />
        </button>

        <!-- Scrollable content area -->
        <div class="invoice-scroll">
        <!-- Printable Invoice Area -->
        <div id="invoice-print-area" class="invoice-body">
          <!-- Header: Logo + INVOICE -->
          <div class="invoice-header">
            <img src="/logo-full.png" alt="Tentaklik" class="invoice-logo" />
            <div class="invoice-header-right">
              <h1 class="invoice-title">INVOICE</h1>
              <span 
                :class="isPaid ? 'bg-emerald-100 text-emerald-700 border-emerald-300' : 'bg-orange-100 text-orange-700 border-orange-300'"
                class="px-2.5 py-0.5 text-xs font-extrabold uppercase rounded-md border inline-block mt-1"
              >
                {{ isPaid ? '✓ PAID' : 'UNPAID / PENDING' }}
              </span>
            </div>
          </div>

          <!-- Meta Info Row -->
          <div class="invoice-meta">
            <div class="invoice-meta-item">
              <span class="invoice-meta-label">Invoice No.</span>
              <span class="invoice-meta-value">{{ transaction?.payment_data?.merchantOrderId || transaction?.id?.substring(0,8) || '-' }}</span>
            </div>
            <div class="invoice-meta-item">
              <span class="invoice-meta-label">Date</span>
              <span class="invoice-meta-value">{{ formatDate(transaction?.created_at) }}</span>
            </div>
            <div class="invoice-meta-item">
              <span class="invoice-meta-label">Payment Method</span>
              <span class="invoice-meta-value">{{ transaction?.payment_data?.paymentName || transaction?.payment_data?.method || 'Transfer' }}</span>
            </div>
          </div>

          <hr class="invoice-divider" />

          <!-- Table-like Item List -->
          <table class="invoice-table">
            <thead>
              <tr>
                <th class="text-left">Item Description</th>
                <th class="text-right">Amount</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <td>{{ transaction?.description || 'Digital Ad Management Service' }}</td>
                <td class="text-right">{{ formatMoney(transaction?.amount) }}</td>
              </tr>
              <tr v-if="Number(transaction?.fee_amount) > 0">
                <td>Service Fee</td>
                <td class="text-right">{{ formatMoney(transaction?.fee_amount) }}</td>
              </tr>
            </tbody>
            <tfoot>
              <tr class="invoice-total-row">
                <td>Total Payable</td>
                <td class="text-right">{{ formatMoney(Number(transaction?.amount || 0) + Number(transaction?.fee_amount || 0)) }}</td>
              </tr>
            </tfoot>
          </table>

          <!-- Footer -->
          <div class="invoice-footer">
